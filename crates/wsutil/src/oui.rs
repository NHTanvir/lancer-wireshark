//! IEEE OUI (Organizationally Unique Identifier) → vendor lookup.
//!
//! Subset of the IEEE registered list, baked in for offline use.
//! See `tools/update-oui` to regenerate from `https://standards-oui.ieee.org/`.

use once_cell::sync::Lazy;
use std::collections::HashMap;

static OUI_TABLE: Lazy<HashMap<[u8; 3], &'static str>> = Lazy::new(|| {
    let mut m = HashMap::with_capacity(OUI_DATA.len());
    for (prefix, name) in OUI_DATA {
        m.insert(*prefix, *name);
    }
    m
});

/// Resolve a MAC's leading three bytes to a vendor name.
pub fn lookup(mac: [u8; 6]) -> Option<&'static str> {
    OUI_TABLE.get(&[mac[0], mac[1], mac[2]]).copied()
}

/// Resolve any prefix (e.g. for OUI:48 or :36 — we only check the /24 portion here).
pub fn lookup_prefix(prefix: [u8; 3]) -> Option<&'static str> {
    OUI_TABLE.get(&prefix).copied()
}

