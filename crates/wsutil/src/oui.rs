#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn looks_up_apple() {
        assert_eq!(lookup_prefix([0x10, 0x40, 0xF3]), Some("Apple"));
    }

    #[test]
    fn looks_up_vmware() {
        assert_eq!(lookup_prefix([0x00, 0x05, 0x69]), Some("VMware"));
    }

    #[test]
    fn unknown_returns_none() {
        assert!(lookup_prefix([0xAA, 0xBB, 0xCC]).is_none());
    }
}
